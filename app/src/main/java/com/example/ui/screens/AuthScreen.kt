            ) {
                Icon(
                    imageVector = Icons.Default.CheckCircle,
                    contentDescription = "RoutineFlow logo",
                    tint = Color.White,
                    modifier = Modifier.size(54.dp)
                )
            }

            Spacer(modifier = Modifier.height(24.dp))

            Text(
                text = "RoutineFlow",
